import { test, expect } from '@playwright/test'

test('public and admin layouts render, navigate and fit the viewport', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /O trabalho de vocês merece/ })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByText(/A plataforma ainda não está aberta para cadastros/)).toBeVisible()
  await page.getByRole('link', { name: /Conheça o projeto/ }).click()
  await expect(page.getByRole('heading', { name: 'Conexão com o backend' })).toBeVisible()
  await expect(page.getByText('Respondendo', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Verificar novamente/ }).click()
  await expect(page.getByRole('button', { name: /Verificar novamente/ })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('validation shows accessible errors and confirms stateless server result', async ({ page }) => {
  await page.goto('/foundation/configuracao')
  await page.getByRole('button', { name: 'Validar campos' }).click()
  await expect(page.getByLabel('Nome da instituição')).toBeFocused()
  await expect(page.getByText('Informe um nome com pelo menos 2 caracteres.')).toBeVisible()
  await page.getByLabel('Nome da instituição').fill('Associação Horizonte')
  await page.getByLabel('Endereço do site').fill('admin')
  await page.getByRole('button', { name: 'Validar campos' }).click()
  await expect(page.getByText('Este endereço está reservado.')).toBeVisible()
  await page.getByLabel('Endereço do site').fill('associacao-horizonte')
  const response = page.waitForResponse('/api/setup/validate')
  await page.getByRole('button', { name: 'Validar campos' }).click()
  expect((await response).status()).toBe(200)
  await expect(page.getByRole('status')).toContainText('Nenhuma instituição foi criada')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.reload()
  await expect(page.getByLabel('Nome da instituição')).toHaveValue('')
})

test('API health and validation have safe, no-store contracts', async ({ request }) => {
  const health = await request.get('/api/health')
  expect(health.status()).toBe(200)
  expect(await health.json()).toEqual({ status: 'ok', service: 'pagino' })
  expect(health.headers()['cache-control']).toContain('no-store')
  expect(health.headers()['x-request-id']).toMatch(/^[a-f0-9-]{36}$/)
  const invalid = await request.post('/api/setup/validate', { data: { name: 'Teste', slug: 'admin', role: 'owner' } })
  expect(invalid.status()).toBe(422)
  expect((await invalid.json()).data.code).toBe('VALIDATION_ERROR')
  const valid = await request.post('/api/setup/validate', { data: { name: 'Teste', slug: 'teste' } })
  expect(await valid.json()).toEqual({ valid: true, persisted: false, data: { name: 'Teste', slug: 'teste' } })
  const crossOrigin = await request.post('/api/setup/validate', { headers: { origin: 'https://untrusted.example' }, data: { name: 'Teste', slug: 'teste' } })
  expect(crossOrigin.status()).toBe(403)
  const noJson = await request.post('/api/setup/validate', { data: 'text' })
  expect(noJson.status()).toBe(415)
  const malformed = await request.post('/api/setup/validate', { headers: { 'content-type': 'application/json' }, data: Buffer.from('{invalid') })
  expect(malformed.status()).toBe(400)
  const tooLarge = await request.post('/api/setup/validate', { data: { name: 'a'.repeat(9000), slug: 'teste' } })
  expect(tooLarge.status()).toBe(413)
})

